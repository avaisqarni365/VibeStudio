/**
 * Bundle the API into a single CommonJS file for the desktop shell.
 *
 * Why bundle: the @vibestudio/* workspace packages point `main` at raw
 * TypeScript (`src/index.ts`), so a plain `tsc` build produces output that
 * `require("@vibestudio/config")` can't resolve at runtime. esbuild inlines
 * those TS packages (and the pure-JS npm deps) into one file.
 *
 * Externals: knex + the DB drivers are left external because knex resolves
 * its dialect modules with dynamic require() that esbuild can't follow. They
 * are installed into dist-bundle/node_modules by the desktop prepare step.
 */
import { build } from "esbuild";
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const apiRoot = join(here, "..");
const outdir = join(apiRoot, "dist-bundle");
mkdirSync(outdir, { recursive: true });

const external = [
  "knex",
  "pg",
  "pg-native",
  "pg-query-stream",
  "sqlite3",
  "better-sqlite3",
  "mysql",
  "mysql2",
  "oracledb",
  "tedious",
];

await build({
  entryPoints: [join(apiRoot, "src", "index.ts")],
  outfile: join(outdir, "api.cjs"),
  bundle: true,
  platform: "node",
  target: "node18",
  format: "cjs",
  sourcemap: true,
  external,
  logLevel: "info",
  // Define so any `import.meta`-free CJS deps behave.
  banner: { js: "/* VibeStudio API bundle — generated by scripts/bundle.mjs */" },
});

// Minimal runtime manifest: only the externals knex needs at runtime.
writeFileSync(
  join(outdir, "package.json"),
  JSON.stringify(
    {
      name: "vibestudio-api-bundle",
      private: true,
      version: "0.0.1",
      main: "api.cjs",
      dependencies: { knex: "^3.1.0", pg: "^8.11.3" },
    },
    null,
    2,
  ),
);

console.log("✓ API bundled → apps/api/dist-bundle/api.cjs");
